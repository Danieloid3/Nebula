#creamos la variable de los tres numeros
n1=float(input("ingresa el primer numero "))
n2=float(input("ingresa el segundo numero "))
n3=float(input("ingresa el tercer numero "))
#creamos la variable de el numero mayor y el menor
mayor=max(n1,n2,n3)
menor=min(n1,n2,n3)
#imprimimos el resultado
print(f"el numero mayor es {mayor} y el numero menor es {menor}")